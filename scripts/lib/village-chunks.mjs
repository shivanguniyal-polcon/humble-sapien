// The body of a village chunk, and the name it is written under.
//
// The build writes one chunk for a State, and the splitter then cuts it into
// one chunk per district. Both use this, so the two cannot drift apart.
//
// The data is the Local Government Directory's village list, carried through
// geoBoundaries gbOpen under the Open Database License 1.0. The share-alike
// obligation attaches to this data, not to the code around it.

export const villageChunkName = (scope) => `${scope}-villages.js`;

export function villageChunkBody({ scope, title, villages, kinds }) {
  const total = Object.values(villages).reduce((n, l) => n + l.length, 0);
  return `// GENERATED by ${scope === 'state' ? 'scripts/build-india-admin.mjs' : 'scripts/split-india-villages.mjs'} — do not edit by hand.
//
// Village names for ${title}, derived from the Local Government Directory
// via geoBoundaries gbOpen. Licensed under the Open Database License (ODbL)
// 1.0: https://opendatacommons.org/licenses/odbl/1-0/
// Share-alike applies to this data. The code that uses it is licensed
// separately.
//
// ${total} villages, keyed by block id. A village can carry a qualifier the
// source records separately, such as the census kind.

export const VILLAGES = ${JSON.stringify(villages)};
export const VILLAGE_KINDS = ${JSON.stringify(kinds)};
`;
}
